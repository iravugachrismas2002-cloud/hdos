// Export of an MVP specification as Markdown so founders can revise it outside HDOS and share it with engineers.
import type { StoredMvpContent } from "./mvp-planner";

const bullets = (items: string[]) => (items.length ? items.map((i) => `- ${i}`).join("\n") : "_None recorded._");

export const specToMarkdown = (projectName: string, version: number, c: StoredMvpContent): string => {
  const parts: string[] = [
    `# ${projectName}: MVP specification (v${version})`,
    `> Draft for human review. Generated by HDOS Venture Builder (${c.meta.generatedBy}). Not validated market evidence, and no source code is changed or deployed from this document.`,
  ];
  if (c.meta.evidenceWarnings.length) parts.push(`## Evidence warnings\n${bullets(c.meta.evidenceWarnings)}`);
  parts.push(
    `## Product vision\n${c.productVision}`,
    `## Problem statement\n${c.problemStatement}`,
    `## Customer personas\n${c.personas.map((p) => `### ${p.name}\n${p.description}\n\nNeeds:\n${bullets(p.needs)}`).join("\n\n")}`,
    `## User journeys\n${c.userJourneys.map((j) => `### ${j.persona}\n${j.steps.map((s, n) => `${n + 1}. ${s}`).join("\n")}`).join("\n\n")}`,
    `## Product requirements\n${bullets(c.productRequirements)}`,
    `## MVP scope\n### Included\n${bullets(c.mvpScope.included)}\n\n### Deferred\n${bullets(c.mvpScope.excluded)}`,
    `## Feature priorities\n${c.featurePriorities.map((f) => `- **${f.priority}** ${f.feature}${f.rationale ? ` (${f.rationale})` : ""}`).join("\n")}`,
    `## User stories\n${bullets(c.userStories)}`,
    `## Acceptance criteria\n${c.acceptanceCriteria.map((a) => `### ${a.story}\n${bullets(a.criteria)}`).join("\n\n")}`,
    `## Functional requirements\n${bullets(c.functionalRequirements)}`,
    `## Non-functional requirements\n${bullets(c.nonFunctionalRequirements)}`,
    `## Technical architecture (proposal)\n${c.technicalArchitecture.overview}\n\nComponents:\n${bullets(c.technicalArchitecture.components)}\n\nRisks:\n${bullets(c.technicalArchitecture.risks)}`,
    `## Database design (proposal)\n${c.databaseDesign.map((d) => `- **${d.entity}**: ${d.purpose} (${d.keyFields.join(", ")})`).join("\n")}`,
    `## API catalogue (proposal)\n${c.apiCatalogue.map((a) => `- \`${a.method} ${a.path}\`: ${a.purpose}`).join("\n")}`,
    `## Development roadmap\n${c.developmentRoadmap.map((r) => `### ${r.phase} (${r.weeks} weeks)\n${bullets(r.deliverables)}`).join("\n\n")}`,
    `## Testing strategy\n${bullets(c.testingStrategy)}`,
    `## Prototype requirements\n${bullets(c.prototypeRequirements)}`,
  );
  return `${parts.join("\n\n")}\n`;
};
